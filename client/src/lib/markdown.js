import { clock, paraNumber } from './format.js';

const ref = (ids, byId) =>
  ids
    .map((id) => {
      const t = byId.get(id)?.start;
      return `¶${paraNumber(id)}${t != null ? ` (${clock(t)})` : ''}`;
    })
    .join(', ');

/** The edition as a Markdown document: overview, chapters, quiz with answers, numbered transcript. */
export function toMarkdown({ title, result, segments }) {
  const byId = new Map(segments.map((s) => [s.id, s]));
  const { overview, quiz } = result;
  const out = [`# ${title}`, '', '_Study edition generated by Stanza. ¶ numbers refer to the numbered transcript at the end._', ''];

  out.push('## Summary', '', overview.summary, '');
  if (overview.themes.length) out.push(`**Themes:** ${overview.themes.join(' · ')}`, '');

  out.push('## Key takeaways', '');
  overview.takeaways.forEach((t, i) => out.push(`${i + 1}. ${t.text} — ${ref(t.segmentIds, byId)}`));
  out.push('');

  out.push('## Chapters', '');
  for (const c of overview.chapters) {
    const time = c.start != null ? `${clock(c.start)}–${clock(c.end)} · ` : '';
    out.push(`### ${c.title}`, '', `_${time}¶${paraNumber(c.startSegmentId)}–${paraNumber(c.endSegmentId)}_`, '', c.explanation, '');
  }

  if (quiz?.questions?.length) {
    out.push('## Quiz', '');
    quiz.questions.forEach((q, i) => {
      out.push(`**${i + 1}. ${q.question}** _(${q.difficulty})_`, '');
      q.options.forEach((o, j) => out.push(`- ${String.fromCharCode(65 + j)}. ${o}`));
      out.push('');
    });
    out.push('### Answers', '');
    quiz.questions.forEach((q, i) => {
      out.push(
        `${i + 1}. **${String.fromCharCode(65 + q.answerIndex)}. ${q.options[q.answerIndex]}** — ${q.explanation}`,
        `   > “${q.quote}” — ${ref(q.segmentIds, byId)}`,
        '',
      );
    });
  }

  out.push('## Transcript', '');
  for (const s of segments) out.push(`**¶${paraNumber(s.id)}**${s.start != null ? ` [${clock(s.start)}]` : ''} ${s.text}`, '');
  return out.join('\n');
}

export function download(filename, text, type) {
  const url = URL.createObjectURL(new Blob([text], { type }));
  const a = Object.assign(document.createElement('a'), { href: url, download: filename });
  document.body.append(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export const slug = (s) =>
  String(s)
    .toLowerCase()
    .replace(/\.[a-z0-9]+$/, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60) || 'episode';
